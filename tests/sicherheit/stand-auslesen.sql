-- Liest den Aufbau der Datenbank aus (nur Struktur, keine Daten) – für schema-stand.sql.
-- Nur lesend; im Supabase-SQL-Editor ausführen und das Ergebnis speichern.
with
pub as (select oid from pg_namespace where nspname = 'public'),
typen as (
  select string_agg(format('create type public.%I as enum (%s);', t.typname,
    (select string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder) from pg_enum e where e.enumtypid = t.oid)), E'\n' order by t.typname) s
  from pg_type t where t.typnamespace = (select oid from pub) and t.typtype = 'e'),
tabs as (
  select string_agg(format('create table public.%I (%s);', c.relname,
    (select string_agg(format('%I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
        case when a.attidentity = 'a' then ' generated always as identity' when a.attidentity = 'd' then ' generated by default as identity' else '' end,
        case when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(ad.adbin, ad.adrelid) || ') stored'
             when ad.adbin is not null and a.attidentity = '' then ' default ' || pg_get_expr(ad.adbin, ad.adrelid) else '' end,
        case when a.attnotnull then ' not null' else '' end), ', ' order by a.attnum)
     from pg_attribute a left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
     where a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped)), E'\n' order by c.relname) s
  from pg_class c where c.relnamespace = (select oid from pub) and c.relkind = 'r'),
funks as (
  select string_agg(pg_get_functiondef(p.oid) || ';', E'\n-- @@\n' order by p.proname, p.oid) s
  from pg_proc p where p.pronamespace = (select oid from pub) and p.prokind in ('f', 'p')
   and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')),
views as (
  select string_agg(format('create or replace view public.%I%s as %s', c.relname,
     case when c.reloptions is not null then ' with (' || array_to_string(c.reloptions, ', ') || ')' else '' end,
     pg_get_viewdef(c.oid)), E'\n-- @@\n' order by c.relname) s
  from pg_class c where c.relnamespace = (select oid from pub) and c.relkind = 'v'),
kons as (
  select string_agg(format('alter table public.%I add constraint %I %s;', c.relname, k.conname, pg_get_constraintdef(k.oid)), E'\n'
     order by case k.contype when 'p' then 1 when 'u' then 2 when 'x' then 3 when 'c' then 4 else 5 end, c.relname, k.conname) s
  from pg_constraint k join pg_class c on c.oid = k.conrelid where c.relnamespace = (select oid from pub) and k.contype in ('p', 'u', 'f', 'c', 'x')),
idx as (
  select string_agg(pg_get_indexdef(i.indexrelid) || ';', E'\n' order by c.relname) s
  from pg_index i join pg_class c on c.oid = i.indexrelid join pg_class t on t.oid = i.indrelid
  where t.relnamespace = (select oid from pub) and not exists (select 1 from pg_constraint k where k.conindid = i.indexrelid)),
trg as (
  select string_agg(pg_get_triggerdef(t.oid) || ';', E'\n' order by c.relname, t.tgname) s
  from pg_trigger t join pg_class c on c.oid = t.tgrelid where c.relnamespace = (select oid from pub) and not t.tgisinternal),
rls as (
  select string_agg(format('alter table public.%I enable row level security;%s', c.relname,
     case when c.relforcerowsecurity then format(' alter table public.%I force row level security;', c.relname) else '' end), E'\n') s
  from pg_class c where c.relnamespace = (select oid from pub) and c.relkind = 'r' and c.relrowsecurity),
pol as (
  select string_agg(format('create policy %I on %I.%I as %s for %s to %s%s%s;', p.policyname, p.schemaname, p.tablename, p.permissive, p.cmd,
     array_to_string(p.roles, ', '),
     case when p.qual is not null then ' using (' || p.qual || ')' else '' end,
     case when p.with_check is not null then ' with check (' || p.with_check || ')' else '' end), E'\n') s
  from pg_policies p where p.schemaname in ('public', 'storage')),
rech_tab as (
  select string_agg(format('grant %s on public.%I to %s;', a.privilege_type, c.relname, case when a.grantee = 0 then 'public' else quote_ident(r.rolname) end), E'\n') s
  from pg_class c cross join lateral aclexplode(c.relacl) a left join pg_roles r on r.oid = a.grantee
  where c.relnamespace = (select oid from pub) and c.relkind in ('r', 'v', 'S') and c.relacl is not null
    and coalesce(r.rolname, 'public') in ('public', 'anon', 'authenticated', 'service_role')),
rech_spalte as (
  select string_agg(format('grant %s (%I) on public.%I to %s;', a.privilege_type, at.attname, c.relname, case when a.grantee = 0 then 'public' else quote_ident(r.rolname) end), E'\n') s
  from pg_attribute at join pg_class c on c.oid = at.attrelid cross join lateral aclexplode(at.attacl) a left join pg_roles r on r.oid = a.grantee
  where c.relnamespace = (select oid from pub) and at.attacl is not null and coalesce(r.rolname, 'public') in ('public', 'anon', 'authenticated', 'service_role')),
rech_fn as (
  select string_agg(format('grant execute on function public.%I(%s) to %s;', p.proname, pg_get_function_identity_arguments(p.oid), case when a.grantee = 0 then 'public' else quote_ident(r.rolname) end), E'\n') s
  from pg_proc p cross join lateral aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) a left join pg_roles r on r.oid = a.grantee
  where p.pronamespace = (select oid from pub) and p.prokind in ('f', 'p') and a.privilege_type = 'EXECUTE'
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
    and coalesce(r.rolname, 'public') in ('public', 'anon', 'authenticated', 'service_role')),
buckets as (
  select string_agg(format('insert into storage.buckets (id, name, public) values (%L, %L, %L) on conflict do nothing;', id, name, public), E'\n') s from storage.buckets)
select E'-- ##TYPEN\n' || (select s from typen) || E'\n-- ##TABELLEN\n' || (select s from tabs)
 || E'\n-- ##FUNKTIONEN\n' || (select s from funks) || E'\n-- ##VIEWS\n' || coalesce((select s from views), '')
 || E'\n-- ##CONSTRAINTS\n' || (select s from kons) || E'\n-- ##INDEXE\n' || coalesce((select s from idx), '')
 || E'\n-- ##TRIGGER\n' || (select s from trg) || E'\n-- ##RLS\n' || (select s from rls) || E'\n-- ##POLICIES\n' || (select s from pol)
 || E'\n-- ##RECHTE\n' || (select s from rech_tab) || E'\n' || coalesce((select s from rech_spalte), '') || E'\n' || (select s from rech_fn)
 || E'\n-- ##BUCKETS\n' || coalesce((select s from buckets), '') || E'\n-- ##ENDE\n' as ddl;
